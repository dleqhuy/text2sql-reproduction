"""Common bounded runner for Vanilla and thin upstream adapters."""

import argparse
import contextlib
import time
from datetime import datetime, timezone
from pathlib import Path

from scripts.common.config import credentials, load_config
from scripts.common.contracts import failure, validate_inputs, validate_predictions
from scripts.common.io import ROOT, db_path, digest, file_hash, read_json, read_jsonl, write_json
from scripts.common.llm import LLM, BudgetExceeded, ProviderFailure
from scripts.common.methods import DIN, MAC, DAILPrepared, Vanilla
from scripts.common.provenance import code_provenance, git_info
from scripts.common.run_store import RunStore
from scripts.common.schema import load_schemas

REPOS = {"din_sql": "Few-shot-NL2SQL-with-prompting", "mac_sql": "MAC-SQL", "dail_sql": "DAIL-SQL"}


def run(args):
    config, creds = load_config(args.config), credentials()
    inputs, manifest = read_jsonl(args.input), read_json(args.manifest)
    validate_inputs(inputs)
    if digest(inputs) not in {manifest["input_hash"], manifest["smoke_input_hash"]}:
        raise ValueError("Input differs from frozen manifest")
    tables = load_schemas(args.tables)
    table_hash = file_hash(args.tables)
    if table_hash not in {
        manifest["source_hashes"]["tables.json"],
        manifest.get("prepared_tables_hash"),
    }:
        raise ValueError("Tables fingerprint mismatch")
    for row in inputs:
        path = db_path(args.db_root, row["db_id"])
        if file_hash(path) != manifest["database_hashes"][row["db_id"]]:
            raise ValueError("DB differs from frozen manifest")
    provenance = code_provenance()
    identity = {
        "method": args.method,
        "model": creds.model,
        "config": config,
        "endpoint_hash": digest(creds.base_url),
        "input_hash": digest(inputs),
        "manifest_hash": digest(manifest),
        "tables_hash": table_hash,
        "code_hash": provenance["code_hash"],
        "dependencies_hash": digest(provenance["dependencies"]),
    }
    repo = ROOT / "third_party" / REPOS[args.method] if args.method in REPOS else None
    if repo:
        provenance["upstream"] = git_info(repo)
        lock = read_json(ROOT / "configs/upstream_lock.json")[args.method]
        if provenance["upstream"]["commit"] != lock["commit"] or provenance["upstream"]["dirty"]:
            raise ValueError("Upstream checkout differs from pinned clean commit")
        identity["upstream"] = provenance["upstream"]
    if args.method == "dail_sql":
        if not args.dail_prompts:
            raise ValueError("DAIL requires --dail-prompts generated by prepare_dail")
        identity["dail_bundle_hash"] = file_hash(args.dail_prompts)
    store = RunStore(args.run_dir, identity, inputs, args.resume)
    write_json(Path(args.run_dir) / "provenance.json", provenance)
    validate_predictions(list(store.rows.values()), inputs, require_complete=False)
    started = datetime.fromisoformat(store.meta["created_at"]).timestamp()

    def allowed():
        return (
            store.request_count < config["max_run_calls"]
            and datetime.now(timezone.utc).timestamp() - started < config["max_run_seconds"]
        )

    llm = LLM(creds, config, store.event, allowed)
    try:
        with (
            (Path(args.run_dir) / "stdout.log").open("a") as stdout,
            (Path(args.run_dir) / "stderr.log").open("a") as stderr,
            contextlib.redirect_stdout(stdout),
            contextlib.redirect_stderr(stderr),
        ):
            if args.method == "vanilla":
                method = Vanilla(llm, tables)
            elif args.method == "din_sql":
                method = DIN(llm, repo, args.tables, inputs)
            elif args.method == "mac_sql":
                method = MAC(llm, repo, args.tables, args.db_root, config["sql_timeout_s"])
            else:
                method = DAILPrepared(llm, args.dail_prompts, inputs, manifest)
            for row in inputs:
                if row["example_id"] in store.rows:
                    continue
                store.current_id = row["example_id"]
                llm.reset()
                start = time.monotonic()
                result = failure(row, args.method, creds.model, "method_error", "Method failed")
                try:
                    if not allowed():
                        raise BudgetExceeded()
                    sql = method.infer(row)
                    if llm.budget_exhausted:
                        raise BudgetExceeded()
                    result.update(predicted_sql=sql, status="ok", error=None)
                except BudgetExceeded:
                    result.update(
                        status="budget_exceeded",
                        error={
                            "type": "budget_exceeded",
                            "stage": "inference",
                            "message": "Run budget exhausted",
                        },
                    )
                except ProviderFailure as exc:
                    result.update(
                        status=exc.kind,
                        error={
                            "type": exc.kind,
                            "stage": "provider",
                            "message": "Provider request failed",
                        },
                    )
                except (ValueError, IndexError, KeyError) as exc:
                    result.update(
                        status="parse_error",
                        error={
                            "type": type(exc).__name__,
                            "stage": "method",
                            "message": "Method output could not be parsed",
                        },
                    )
                except Exception as exc:
                    # Do not log arbitrary upstream exception messages (may contain HTTP credentials).
                    result["error"]["type"] = type(exc).__name__
                result.update(latency_ms=(time.monotonic() - start) * 1000, **llm.measurements())
                if args.method == "dail_sql":
                    result["variant"] = method.variant
                validate_predictions([result], [row])
                store.save(result)
        validate_predictions(list(store.rows.values()), inputs)
        store.finish("completed")
    except BaseException:
        store.finish("interrupted")
        raise
    finally:
        store.close()
    ok = sum(r["status"] == "ok" for r in store.rows.values())
    print(f"Finished {args.method}: {ok}/{len(inputs)} SQL outputs; artifacts in {args.run_dir}")


def main(default_method=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--method",
        choices=["vanilla", *REPOS],
        default=default_method,
        required=default_method is None,
    )
    parser.add_argument("--input", required=True)
    parser.add_argument("--manifest", required=True)
    parser.add_argument("--tables", required=True)
    parser.add_argument("--db-root", required=True, type=Path)
    parser.add_argument("--run-dir", required=True, type=Path)
    parser.add_argument("--config")
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--dail-prompts")
    args = parser.parse_args()
    run(args)


if __name__ == "__main__":
    main()
